//! A presentation: the package plus navigation through it — slides in order, each slide's
//! layout, master, theme and notes, and the slide size. Everything is read straight from the
//! parts (the package is the model, as in the JS library), so edits are XML edits and files
//! round-trip losslessly.

use crate::color::{ColorMap, Scheme};
use crate::opc::{self, Package};
use crate::xml::Element;

pub const EMU_PER_INCH: f64 = 914_400.0;
pub const EMU_PER_PT: f64 = 12_700.0;
pub const EMU_PER_PX: f64 = 9_525.0;

pub const NS_A: &str = "http://schemas.openxmlformats.org/drawingml/2006/main";
pub const NS_P: &str = "http://schemas.openxmlformats.org/presentationml/2006/main";
pub const NS_R: &str = "http://schemas.openxmlformats.org/officeDocument/2006/relationships";

#[derive(Clone, Debug, Default)]
pub struct Theme {
    pub name: String,
    pub scheme: Scheme,
    pub major: Fonts,
    pub minor: Fonts,
    pub fill_styles: Vec<Element>,
    pub line_styles: Vec<Element>,
    pub effect_styles: Vec<Element>,
    pub bg_fill_styles: Vec<Element>,
}

#[derive(Clone, Debug, Default)]
pub struct Fonts { pub latin: String, pub ea: String, pub cs: String }

impl Theme {
    pub fn from_xml(t: &Element) -> Theme {
        let el = t.child("a:themeElements");
        let fonts = |which: &str| -> Fonts {
            let f = el.and_then(|e| e.path(&format!("a:fontScheme/{which}")));
            let face = |k: &str| f.and_then(|f| f.child(k)).and_then(|x| x.attr("typeface")).unwrap_or("").to_string();
            Fonts { latin: face("a:latin"), ea: face("a:ea"), cs: face("a:cs") }
        };
        let list = |path: &str| -> Vec<Element> { el.and_then(|e| e.path(path)).map(|l| l.elements().cloned().collect()).unwrap_or_default() };
        Theme {
            name: t.attr("name").unwrap_or("").to_string(),
            scheme: el.and_then(|e| e.child("a:clrScheme")).map(Scheme::from_xml).unwrap_or_default(),
            major: fonts("a:majorFont"),
            minor: fonts("a:minorFont"),
            fill_styles: list("a:fmtScheme/a:fillStyleLst"),
            line_styles: list("a:fmtScheme/a:lnStyleLst"),
            effect_styles: list("a:fmtScheme/a:effectStyleLst"),
            bg_fill_styles: list("a:fmtScheme/a:bgFillStyleLst"),
        }
    }
    /// A typeface name with theme references (+mj-lt, +mn-ea, …) resolved.
    pub fn typeface(&self, face: &str) -> String {
        let f = match face {
            "+mj-lt" => &self.major.latin, "+mj-ea" => &self.major.ea, "+mj-cs" => &self.major.cs,
            "+mn-lt" => &self.minor.latin, "+mn-ea" => &self.minor.ea, "+mn-cs" => &self.minor.cs,
            other => return other.to_string(),
        };
        if f.is_empty() { if face.starts_with("+mj") { self.major.latin.clone() } else { self.minor.latin.clone() } } else { f.clone() }
    }
}

#[derive(Clone, Debug)]
pub struct Presentation {
    pub pkg: Package,
    /// "ppt/presentation.xml".
    pub main: String,
}

/// Blank decks generated by the JS library (createPresentation), 16:9 and 4:3.
pub const BLANK_16X9: &[u8] = include_bytes!("../assets/blank-16x9.pptx");
pub const BLANK_4X3: &[u8] = include_bytes!("../assets/blank-4x3.pptx");

impl Presentation {
    pub fn open(bytes: &[u8]) -> Result<Presentation, String> {
        let pkg = Package::open(bytes)?;
        let main = pkg.related("", opc::RT_OFFICE_DOC).unwrap_or_else(|| "ppt/presentation.xml".to_string());
        if pkg.xml(&main).is_none() { return Err("Not a PowerPoint presentation".into()); }
        let p = Presentation { pkg, main };
        // Fonts the file brings with it are used for its text.
        p.load_embedded_fonts();
        Ok(p)
    }
    pub fn new_blank(widescreen: bool) -> Presentation {
        Presentation::open(if widescreen { BLANK_16X9 } else { BLANK_4X3 }).expect("blank deck")
    }
    pub fn save(&self) -> Result<Vec<u8>, String> { self.pkg.save() }

    pub fn root(&self) -> &Element { self.pkg.xml(&self.main).expect("presentation part") }
    pub fn root_mut(&mut self) -> &mut Element { let m = self.main.clone(); self.pkg.xml_mut(&m).expect("presentation part") }

    /// Slide size in EMU.
    pub fn size(&self) -> (f64, f64) {
        let s = self.root().child("p:sldSz");
        (s.and_then(|s| s.attr_f64("cx")).unwrap_or(12_192_000.0), s.and_then(|s| s.attr_f64("cy")).unwrap_or(6_858_000.0))
    }
    pub fn set_size(&mut self, cx: i64, cy: i64) {
        let s = self.root_mut().ensure_at("p:sldSz", &["p:notesSz", "p:smartTags", "p:embeddedFontLst", "p:custShowLst", "p:photoAlbum", "p:custDataLst", "p:kinsoku", "p:defaultTextStyle", "p:modifyVerifier", "p:extLst"]);
        s.set_attr("cx", cx.to_string());
        s.set_attr("cy", cy.to_string());
        s.remove_attr("type");
    }

    /// Slide part names in order.
    pub fn slides(&self) -> Vec<String> {
        let Some(list) = self.root().child("p:sldIdLst") else { return vec![] };
        list.children_named("p:sldId").filter_map(|s| s.attr("r:id")).filter_map(|id| self.pkg.rel_target(&self.main, id)).collect()
    }
    pub fn slide(&self, part: &str) -> Option<&Element> { self.pkg.xml(part) }
    pub fn layout_of(&self, slide: &str) -> Option<String> { self.pkg.related(slide, opc::RT_LAYOUT) }
    pub fn master_of(&self, layout: &str) -> Option<String> { self.pkg.related(layout, opc::RT_MASTER) }
    pub fn notes_of(&self, slide: &str) -> Option<String> { self.pkg.related(slide, opc::RT_NOTES) }
    pub fn theme_part(&self, master: &str) -> Option<String> { self.pkg.related(master, opc::RT_THEME) }
    pub fn theme(&self, master: &str) -> Theme {
        self.theme_part(master).and_then(|t| self.pkg.xml(&t)).map(Theme::from_xml).unwrap_or_default()
    }
    /// Masters in order.
    pub fn masters(&self) -> Vec<String> {
        let Some(list) = self.root().child("p:sldMasterIdLst") else { return vec![] };
        list.elements().filter_map(|s| s.attr("r:id")).filter_map(|id| self.pkg.rel_target(&self.main, id)).collect()
    }
    /// A master's layouts in order.
    pub fn layouts(&self, master: &str) -> Vec<String> {
        let Some(list) = self.pkg.xml(master).and_then(|m| m.child("p:sldLayoutIdLst")) else { return vec![] };
        list.elements().filter_map(|s| s.attr("r:id")).filter_map(|id| self.pkg.rel_target(master, id)).collect()
    }
    pub fn all_layouts(&self) -> Vec<String> { self.masters().iter().flat_map(|m| self.layouts(m)).collect() }
    /// A layout's name ("Title Slide") and type ("title").
    pub fn layout_name(&self, layout: &str) -> String {
        self.pkg.xml(layout).and_then(|l| l.child("p:cSld")).and_then(|c| c.attr("name")).unwrap_or("Layout").to_string()
    }
    pub fn layout_type(&self, layout: &str) -> String { self.pkg.xml(layout).and_then(|l| l.attr("type")).unwrap_or("cust").to_string() }

    /// The chain a slide inherits from: (slide, layout, master).
    pub fn chain(&self, slide: &str) -> (Option<String>, Option<String>) {
        let layout = self.layout_of(slide);
        let master = layout.as_deref().and_then(|l| self.master_of(l));
        (layout, master)
    }
    /// The effective color map for a slide (the master's, overridden by the layout, then slide).
    pub fn color_map(&self, part: &str) -> ColorMap {
        let (layout, master) = if self.pkg.xml(part).is_some_and(|e| e.is("p:sldMaster")) { (None, Some(part.to_string())) } else if self.pkg.xml(part).is_some_and(|e| e.is("p:sldLayout")) { (Some(part.to_string()), self.master_of(part)) } else { self.chain(part) };
        let base = master.as_deref().and_then(|m| self.pkg.xml(m)).and_then(|m| m.child("p:clrMap")).map(ColorMap::from_xml).unwrap_or_default();
        let after_layout = base.overlay(layout.as_deref().and_then(|l| self.pkg.xml(l)).and_then(|l| l.child("p:clrMapOvr")));
        if self.pkg.xml(part).is_some_and(|e| e.is("p:sld")) { after_layout.overlay(self.pkg.xml(part).and_then(|s| s.child("p:clrMapOvr"))) } else { after_layout }
    }
    /// The master (and so theme) a part belongs to.
    pub fn master_for(&self, part: &str) -> Option<String> {
        let root = self.pkg.xml(part)?;
        if root.is("p:sldMaster") { Some(part.to_string()) } else if root.is("p:sldLayout") { self.master_of(part) } else { self.chain(part).1 }
    }

    /// Is the slide hidden (skipped in the slide show)?
    pub fn hidden(&self, slide: &str) -> bool { self.pkg.xml(slide).and_then(|s| s.attr("show")).is_some_and(|v| v == "0" || v == "false") }

    /// The speaker notes' text.
    pub fn notes_text(&self, slide: &str) -> String {
        let Some(n) = self.notes_of(slide).and_then(|n| self.pkg.xml(&n).cloned()) else { return String::new() };
        let Some(tree) = n.path("p:cSld/p:spTree") else { return String::new() };
        for sp in tree.children_named("p:sp") {
            let ph = sp.path("p:nvSpPr/p:nvPr/p:ph");
            if ph.and_then(|p| p.attr("type")) == Some("body") {
                return sp.child("p:txBody").map(|tb| tb.children_named("a:p").map(|p| p.children_named("a:r").map(|r| r.child("a:t").map(|t| t.text()).unwrap_or_default()).collect::<String>()).collect::<Vec<_>>().join("\n")).unwrap_or_default();
            }
        }
        String::new()
    }

    /// A slide's title text (its title placeholder), for the outline and navigator.
    pub fn slide_title(&self, slide: &str) -> String {
        let Some(tree) = self.pkg.xml(slide).and_then(|s| s.path("p:cSld/p:spTree")) else { return String::new() };
        for sp in tree.children_named("p:sp") {
            let t = sp.path("p:nvSpPr/p:nvPr/p:ph").and_then(|p| p.attr("type"));
            if matches!(t, Some("title") | Some("ctrTitle")) {
                return sp.child("p:txBody").map(|tb| tb.children_named("a:p").map(|p| p.children_named("a:r").map(|r| r.child("a:t").map(|t| t.text()).unwrap_or_default()).collect::<String>()).collect::<Vec<_>>().join(" ")).unwrap_or_default();
            }
        }
        String::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn opens_blank_and_sample() {
        let p = Presentation::new_blank(true);
        assert_eq!(p.size(), (12_192_000.0, 6_858_000.0));
        assert!(p.slides().is_empty());
        assert_eq!(p.all_layouts().len(), 11);
        let m = &p.masters()[0];
        let t = p.theme(m);
        assert!(t.scheme.get("accent1").is_some());
        assert_eq!(t.typeface("+mj-lt"), t.major.latin);

        let s = Presentation::open(include_bytes!("../tests/fixtures/sample.pptx")).unwrap();
        let slides = s.slides();
        assert_eq!(slides.len(), 2);
        assert_eq!(s.slide_title(&slides[0]), "Qalam Slides");
        assert_eq!(s.slide_title(&slides[1]), "Agenda");
        assert!(s.layout_of(&slides[0]).is_some());
        // Saving and reopening keeps every slide.
        let again = Presentation::open(&s.save().unwrap()).unwrap();
        assert_eq!(again.slides().len(), 2);
    }
}
