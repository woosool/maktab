// Export the JS editor's command icons (documents/src/ui/command-icons.js, original MIT drawings)
// as self-contained SVGs for the Rust app: CSS classes from command-icons.css and the gradient defs
// from index.html are resolved into presentation attributes (light theme), and the 1px
// non-scaling strokes are converted for 16px and 32px renderings.
//
//   node word/tools/export-icons.mjs   →   word/app/src/icon_data.rs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const js = path.join(here, '../../documents');
const { COMMAND_ICONS } = await import(path.join(js, 'src/ui/command-icons.js'));

const css = readFileSync(path.join(js, 'src/styles/command-icons.css'), 'utf8');
const rootBlock = css.slice(css.indexOf(':root {'), css.indexOf('}', css.indexOf(':root {')));
const vars = Object.fromEntries([...rootBlock.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
vars['ico-knock'] = '#ffffff';
const v = (name) => vars[name] ?? '#000';
const ink = v('ico-ink');

const html = readFileSync(path.join(js, 'index.html'), 'utf8');
const defs = html.slice(html.indexOf('<linearGradient id="ico-g-paper"'), html.lastIndexOf('</linearGradient>') + '</linearGradient>'.length)
  .replace(/style="stop-color:var\(--([\w-]+)\)"/g, (_, n) => `stop-color="${v(n)}"`)
  .replace(/\s*\n\s*/g, '');

// Rules in stylesheet order: [class, properties]. `sw` values are px (non-scaling) unless `scaled`.
const g = (id) => `url(#ico-g-${id})`;
const RULES = [
  ['thick', { sw: 1.3 }], ['grip', { sw: 1.9 }], ['dash', { dash: 1.5, cap: 'butt' }], ['ln', { opacity: 0.35 }],
  ['o', { fill: 'none', stroke: ink }], ['of', { fill: g('paper'), stroke: v('ico-line') }], ['s', { fill: ink, stroke: 'none' }],
  ['w', { fill: 'none', stroke: v('ico-paper-top') }], ['tx', { fill: ink, stroke: 'none' }], ['txb', { fill: g('blue-solid'), stroke: 'none' }],
  ['txb2', { fill: v('ico-blue'), stroke: 'none' }], ['txw', { fill: '#fff', stroke: 'none' }], ['knock', { fill: v('ico-knock'), stroke: 'none' }],
  ['wh', { fill: 'none', stroke: '#fff' }], ['glint', { fill: '#fff', stroke: 'none', opacity: 0.85 }], ['glassy', { 'fill-opacity': 0.78 }],
  ...['of', 'bf', 'gf', 'rf', 'yf', 'nf', 'pf'].map((c) => [c, { sw: 0.75 }]),
  ...[['b', 'blue'], ['g', 'green'], ['r', 'red'], ['n', 'amber'], ['p', 'purple']].flatMap(([c, hue]) => [
    [c, { fill: 'none', stroke: v(`ico-${hue}`) }], [`${c}f`, { fill: g(`${hue}-soft`), stroke: v(`ico-${hue}`) }],
    [`${c}s`, { fill: g(`${hue}-solid`), stroke: 'none' }], [`${c}w`, { fill: g(`${hue}-soft`), stroke: 'none' }],
  ]),
  ['y', { fill: 'none', stroke: v('ico-yellow'), sw: 2.5 }], ['yf', { fill: g('yellow-soft'), stroke: v('ico-amber') }], ['ys', { fill: g('yellow-solid'), stroke: 'none' }],
  ['txfx', { fill: g('blue-soft'), stroke: v('ico-blue') }],
];

function convert(body, size) {
  const k = 20 / size; // viewBox units per px
  const stack = []; // classes of open <g> ancestors
  return body.replace(/<(\/?)([\w:]+)([^>]*?)(\/?)>/g, (tag, close, name, attrs, selfClose) => {
    if (close) { if (name === 'g') stack.pop(); return tag; }
    const classes = (attrs.match(/class="([^"]*)"/)?.[1] ?? '').split(/\s+/).filter(Boolean);
    const inText = stack.flat().some((c) => ['tx', 'txb', 'txw', 'txfx'].includes(c));
    const inFx = stack.flat().includes('txfx');
    const p = { sw: 0.9, cap: 'round' };
    for (const [c, props] of RULES) if (classes.includes(c)) Object.assign(p, props);
    if (inText && name === 'path') { p.stroke = inFx ? undefined : 'none'; }
    const out = [];
    if (p.fill) out.push(`fill="${p.fill}"`);
    if (p.stroke) out.push(`stroke="${p.stroke}"`);
    // Lettering paths are in font units and scale; txfx outlines are 40 units wide.
    const sw = inFx && name === 'path' ? 40 : inText ? null : +(p.sw * k).toFixed(3);
    if (sw !== null) out.push(`stroke-width="${sw}"`);
    out.push(`stroke-linecap="${p.cap}"`, 'stroke-linejoin="round"');
    if (p.dash) out.push(`stroke-dasharray="${+(p.dash * k).toFixed(3)} ${+(p.dash * k).toFixed(3)}"`);
    if (p.opacity !== undefined) out.push(`opacity="${p.opacity}"`);
    if (p['fill-opacity'] !== undefined) out.push(`fill-opacity="${p['fill-opacity']}"`);
    if (name === 'g' && !selfClose) stack.push(classes);
    return `<${name}${attrs.replace(/\s*class="[^"]*"/, '')} ${out.join(' ')}${selfClose}>`;
  });
}

const rust = (s) => `r##"${s}"##`;
const names = Object.keys(COMMAND_ICONS).sort();
let out = `// Generated by word/tools/export-icons.mjs from documents/src/ui/command-icons.js (MIT). Do not edit.\n\n`;
out += `/// Gradients shared by every icon.\npub const DEFS: &str = ${rust(defs)};\n\n`;
out += `/// (name, body for 16px, body for 32px) in a 20-unit viewBox, sorted by name.\npub static ICONS: &[(&str, &str, &str)] = &[\n`;
for (const name of names) out += `    ("${name}", ${rust(convert(COMMAND_ICONS[name], 16))}, ${rust(convert(COMMAND_ICONS[name], 32))}),\n`;
out += '];\n';
writeFileSync(path.join(here, '../app/src/icon_data.rs'), out);
console.log(`${names.length} icons → app/src/icon_data.rs (${(out.length / 1024).toFixed(0)} KB)`);
