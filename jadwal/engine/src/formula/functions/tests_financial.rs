//! Financial functions against Excel's documented results.
use super::tests::calc;

fn close(f: &str, want: f64, tol: f64) {
    let got = calc(&[], f);
    let v: f64 = got.parse().unwrap_or_else(|_| panic!("{f} gave {got}"));
    assert!((v - want).abs() <= tol, "{f} = {v}, want {want}");
}

