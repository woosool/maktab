#[test]
fn cash_flows() {
    close("=NPV(0.1,-10000,3000,4200,6800)", 1188.4434123, 1e-6);
    close("=IRR({-70000,12000,15000,18000,21000,26000})", 0.0866309, 1e-7);
    close("=MIRR({-120000,39000,30000,21000,37000,46000},0.1,0.12)", 0.1260941, 1e-7);
    close("=XNPV(0.09,{-10000,2750,4250,3250,2750},{39448,39508,39751,39859,39904})", 2086.6476, 1e-3);
    close("=XIRR({-10000,2750,4250,3250,2750},{39448,39508,39751,39859,39904})", 0.3733625, 1e-6);
    close("=XIRR({-100,110},{44000,44365})", 0.1, 1e-8);
    assert_eq!(calc(&[], "=IRR({1,2,3})"), "#NUM!");
}

